putaran = 5
jarak_km = 14
pi = 3.141592653589793

keliling = jarak_km / putaran
r = keliling / (2 * pi)

print("Diketahui:")
print(f"Pak Dengklek mengelilingi taman = {putaran} Putaran")
print(f"Jarak tempuh Pak Dengklek = {jarak_km} Kilometer")
print("\nJawaban:")
print(f"Jari-jari taman yang dikelilingi Pak Dengklek adalah {r:.2f} Kilometer")